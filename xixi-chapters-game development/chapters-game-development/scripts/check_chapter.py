#!/usr/bin/env python3
"""Validate a development tree and emit a five-column export intermediate.
Not a Chapters runtime, official audit, or conditional-state evaluator.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path

EMOTIONS = {'neutral','smile','laughing','shy','angry','shocked','sad','flirty'}
TYPES = {'text','Choice1','Choice2','Choice3','Premium Choice','Premium choice2',
         'Premium_Sub_Choice','Sub_Choice 1','Sub_Choice2','Sub_Sub_Choice 1','Sub_Sub_Choice2'}
PALETTE = ['#E4EFFA','#F8E6ED','#E4F2E7','#FFF1D6','#EDE6F7','#E1F2F1']
WORDS = re.compile(r"[A-Za-z]+(?:['’][A-Za-z]+)*")

class Checker:
    def __init__(self, fragment=False):
        self.fragment=fragment; self.errors=[]; self.warnings=[]; self.ids=set()
        self.rows=[]; self.groups=[]; self.color_index=0; self.allowed=TYPES.copy()

    def issue(self, severity, code, loc, message):
        (self.errors if severity=='error' else self.warnings).append({'code':code,'at':loc,'message':message})

    def unique(self, obj):
        ident=obj.get('id')
        if not isinstance(ident,str) or not re.fullmatch(r'[A-Za-z0-9_-]+',ident):
            raise ValueError('Every node and branch needs an ASCII id using letters, digits, _ or -.')
        if ident in self.ids: self.issue('error','duplicate_id',ident,'ID must be unique.')
        self.ids.add(ident); return ident

    @staticmethod
    def keys(obj, allowed, loc):
        if not isinstance(obj,dict): raise ValueError(f'{loc}: expected object')
        extra=set(obj)-set(allowed)
        if extra: raise ValueError(f'{loc}: unsupported fields {sorted(extra)}')

    def text(self, value, loc, character):
        if not isinstance(value,str) or not value.strip(): raise ValueError(f'{loc}: empty or invalid text')
        if len(value)>120: self.issue('error','character_limit',loc,f'{len(value)} characters; limit 120.')
        if character not in {'Narration','Narration_PopUp','Choice'} and len(value)>90:
            self.issue('warning','long_dialogue',loc,f'{len(value)} characters; prefer 90 or fewer.')
        if '\n' in value or '\r' in value: self.issue('warning','multiline_cell',loc,'Split display beats into separate rows.')
        if re.search(r'\[[^\]]+\]|<[^>]+>',value):
            self.issue('warning','runtime_length',loc,'Placeholder/rich text counted literally; verify final displayed length.')
        return value

    def branch_type(self, depth, index, paid):
        if depth==1: return ('Premium Choice' if index==1 else 'Premium choice2' if index==2 else f'Premium choice{index}') if paid else f'Choice{index}'
        if depth==2: return 'Premium_Sub_Choice' if paid else ('Sub_Choice 1' if index==1 else f'Sub_Choice{index}')
        if depth==3 and not paid: return 'Sub_Sub_Choice 1' if index==1 else f'Sub_Sub_Choice{index}'
        return f'Unsupported_depth_{depth}_{index}'

    def append(self, ident, typ, char, script, emotion, thought, scope, kind, price=None):
        if typ not in self.allowed: self.issue('error','text_type',ident,f'{typ!r} is outside the confirmed enumeration.')
        if emotion not in EMOTIONS: self.issue('error','emotion',ident,f'Invalid emotion {emotion!r}.')
        if thought not in {'yes','no'}: self.issue('error','thought_bubble',ident,'Use yes or no.')
        if char in {'Narration','Narration_PopUp','Choice'} and thought!='no':
            self.issue('error','narrator_thought',ident,'Thought Bubble yes belongs to a character inner monologue.')
        self.rows.append({'id':ident,'text_type':typ,'character':char,'script':self.text(script,ident,char),
                          'emotion':emotion,'thought_bubble':thought,'kind':kind,'price':price,
                          'group_id':scope.get('group_id',''),'branch_id':scope.get('branch_id',''),
                          'parent_branch':scope.get('parent_branch',''),'depth':scope.get('depth',0),
                          'color':scope.get('color','#FFFFFF'),'excel_row':len(self.rows)+2})

    def sequence(self, nodes, scope=None, paid_ancestor=False):
        if not isinstance(nodes,list) or not nodes: raise ValueError('Every sequence must have at least one node.')
        scope=scope or {}; total=dict(lo=0,hi=0,free_lo=0,free_hi=0,spend=0,body=0,words=0)
        for node in nodes:
            if not isinstance(node,dict): raise ValueError('Node must be an object.')
            ident=self.unique(node)
            if node.get('kind')=='line':
                self.keys(node,{'id','kind','character','script','emotion','thought_bubble'},ident)
                char=node.get('character')
                if not isinstance(char,str) or not char.strip() or char=='Choice':
                    raise ValueError(f'{ident}: line needs a character; buttons are generated by choice nodes.')
                self.append(ident,scope.get('type','text'),char,node.get('script'),node.get('emotion'),node.get('thought_bubble'),scope,'line')
                for key in ['lo','hi','free_lo','free_hi','body']: total[key]+=1
                total['words']+=len(WORDS.findall(node['script']))
                continue
            if node.get('kind')!='choice': raise ValueError(f'{ident}: unsupported node kind; conditionals require an engine workflow.')
            self.keys(node,{'id','kind','category','motivation','branches'},ident)
            category=node.get('category'); branches=node.get('branches')
            if category not in {'FC','PC','PO','customization'}: raise ValueError(f'{ident}: invalid category')
            if not isinstance(branches,list) or len(branches)<2: raise ValueError(f'{ident}: need at least two branches')
            prices=[b.get('price') if isinstance(b,dict) else None for b in branches]
            if any(type(p) is not int or p<0 for p in prices): raise ValueError(f'{ident}: prices must be nonnegative integers')
            paid=[p for p in prices if p>0]
            if category=='FC' and paid: self.issue('error','fc_paid',ident,'FC cannot contain paid branches.')
            if category in {'PC','PO'}:
                if not paid or prices.count(0)!=1: self.issue('error','free_exit',ident,'PC/PO needs paid content and exactly one free branch.')
                if prices not in [[17,0],[17,12,0],[17,12,10,0]]:
                    self.issue('error','price_ladder',ident,'Supported ladders are 17/0, 17/12/0, 17/12/10/0. Exceptions need another confirmed profile.')
                if not isinstance(node.get('motivation'),str) or not node['motivation'].strip():
                    self.issue('error','motivation',ident,'Record the specific purchase motivation.')
            if category=='customization' and paid: self.issue('error','paid_customization',ident,'Paid creation assets require a separate confirmed profile.')
            if category=='FC' and not scope and len(branches)!=3:
                self.issue('warning','fc_count',ident,'Default independent FC has three distinct branches.')
            depth=scope.get('depth',0)+1
            if paid and depth>1 and not paid_ancestor:
                self.issue('error','nested_without_purchase',ident,'Nested paid group without a paid ancestor requires explicit reachability design.')
            level=2 if paid_ancestor else 1
            self.groups.append({'id':ident,'category':category,'level':level,'depth':depth,'prices':prices,
                                'motivation':node.get('motivation',''),'parent_branch':scope.get('branch_id','')})
            stats=[]
            for i,b in enumerate(branches,1):
                self.keys(b,{'id','price','button','nodes'},ident)
                bid=self.unique(b); price=b['price']
                typ=self.branch_type(depth,i,price>0)
                color=PALETTE[self.color_index%len(PALETTE)]; self.color_index+=1
                if color==scope.get('color'):
                    color=PALETTE[self.color_index%len(PALETTE)]; self.color_index+=1
                bs={'type':typ,'group_id':ident,'branch_id':bid,'parent_branch':scope.get('branch_id',''),'depth':depth,'color':color}
                self.append(bid,typ,'Choice',b.get('button'),'neutral','no',bs,'button',price)
                st=self.sequence(b.get('nodes'),bs,paid_ancestor or price>0); stats.append(st)
                if not self.fragment:
                    if price>0 and st['body']<10: self.issue('error','paid_return_lines',bid,f'Shortest purchased branch has {st["body"]} body lines; need 10.')
                    if price>0 and level==1 and category=='PC' and st['words']<100:
                        self.issue('error','l1_words',bid,f'Shortest branch has {st["words"]} English body words; need 100 for shared-profile compatibility.')
                    if category=='FC' and st['body']<3: self.issue('error','fc_return_lines',bid,'FC branch needs at least three body lines.')
            for key in ['lo','body','words']: total[key]+=min(s[key] for s in stats)+(1 if key=='lo' else 0)
            total['hi']+=max(s['hi'] for s in stats)+1
            free=[s for p,s in zip(prices,stats) if p==0]
            if not free:
                self.issue('error','no_free_path',ident,'No free route through this menu.')
            else:
                total['free_lo']+=min(s['free_lo'] for s in free)+1
                total['free_hi']+=max(s['free_hi'] for s in free)+1
            total['spend']+=max(p+s['spend'] for p,s in zip(prices,stats))
        return total

    def run(self, data):
        self.keys(data,{'chapter','title','core_emotion','nodes','extra_text_types'},'chapter')
        if type(data.get('chapter')) is not int or not 1<=data['chapter']<=20: raise ValueError('chapter must be 1..20')
        for field in ['title','core_emotion']:
            if not isinstance(data.get(field),str) or not data[field].strip(): raise ValueError(f'Missing {field}')
        extra=data.get('extra_text_types',[])
        if not isinstance(extra,list) or not all(isinstance(t,str) and t for t in extra): raise ValueError('Invalid extra_text_types')
        if extra: self.issue('warning','extended_types','chapter','Verify project authorization for extra Text Types.')
        self.allowed.update(extra)
        paths=self.sequence(data['nodes'])
        if not self.fragment and not 500<=len(self.rows)<=600:
            self.issue('error','written_rows','chapter',f'{len(self.rows)} valid expanded rows; need 500–600.')
        count=lambda cat,level=None:sum(g['category'] in cat and (level is None or g['level']==level) for g in self.groups)
        metrics={'written_rows':len(self.rows),'physical_groups':len(self.groups),
                 'narrative_l1':count({'PC'},1),'l1_including_po':count({'PC','PO'},1),
                 'l2_including_nested_po':count({'PC','PO'},2),'fc_groups':count({'FC'}),
                 'po_groups':count({'PO'}),'customization_groups':count({'customization'}),
                 'paid_buttons':sum(r['kind']=='button' and r['price']>0 for r in self.rows),
                 'route_rows_min':paths['lo'],'route_rows_max':paths['hi'],
                 'all_free_route_rows_min':paths['free_lo'],'all_free_route_rows_max':paths['free_hi'],
                 'maximum_route_gems':paths['spend']}
        return {'format':'chapters-development.checked-v1','mode':'fragment' if self.fragment else 'chapter',
                'chapter':data['chapter'],'title':data['title'],'core_emotion':data['core_emotion'],
                'passed':not self.errors,'errors':self.errors,'warnings':self.warnings,
                'metrics':metrics,'rows':self.rows,'groups':self.groups,
                'limitations':['No official audit or runtime validation.','No conditional callbacks or entitlement deduplication.','No semantic payoff or merge-fact verification.']}

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('input',type=Path);parser.add_argument('--out',type=Path,required=True)
    parser.add_argument('--fragment',action='store_true');args=parser.parse_args()
    if args.input.resolve()==args.out.resolve(): parser.error('Output must differ from input.')
    checker=Checker(args.fragment)
    try:
        raw=args.input.read_bytes();data=json.loads(raw)
        result=checker.run(data);result['source_sha256']=hashlib.sha256(raw).hexdigest()
    except (ValueError,KeyError,TypeError,RecursionError,OSError) as e:
        result={'format':'chapters-development.checked-v1','passed':False,'errors':checker.errors+[{'code':'schema','message':str(e)}],'warnings':checker.warnings}
    args.out.parent.mkdir(parents=True,exist_ok=True)
    args.out.write_text(json.dumps(result,ensure_ascii=False,indent=2),encoding='utf-8')
    print(json.dumps({k:result[k] for k in ['passed','mode','metrics','errors','warnings'] if k in result},ensure_ascii=False,indent=2))
    return 0 if result['passed'] else 1

if __name__=='__main__':raise SystemExit(main())
